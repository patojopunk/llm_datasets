async def process_skill_event(
    event: dict,
    registry_url: str,
    skills_directory: str,
):
    """
    Process an event generated by SkillWatcher.

    Args:
        event: filesystem event containing action, path,
            and optionally registration_key
        registry_url: registry endpoint
        skills_directory: root directory containing skills
    """

    action = event["action"]

    # New or modified SKILL.md
    if action == "upsert":
        await register_skill(
            registry_url=registry_url,
            skill_path=event["path"],
            skills_directory=skills_directory,
        )
        return

    # Deleted SKILL.md
    if action == "delete":
        await deregister_skill(
            registry_url=registry_url,
            registration_key=event["registration_key"],
        )
        return
